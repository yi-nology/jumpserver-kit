// The mechanics three guards share get their own test: if THIS file's
// parsing goes quiet, every guard built on it passes vacuously — the exact
// failure the guards exist to prevent, arriving one level up.

func TestIsGeneratedReadsTheHeaderNotTheName(t *testing.T) {
	dir := t.TempDir()
	gen := filepath.Join(dir, "model.go")
	hand := filepath.Join(dir, "output.go")
	if err := os.WriteFile(gen, []byte("// Code generated by thriftgo. DO NOT EDIT.\npackage p\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(hand, []byte("package p\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if !IsGenerated(gen) {
		t.Error("the thriftgo header was not recognized")
	}
	if IsGenerated(hand) {
		t.Error("a hand-written file was taken for generated output")
	}
	if IsGenerated(filepath.Join(dir, "gone.go")) {
		t.Error("a missing file was taken for generated output")
	}
}

func TestDeclaredSeesFieldsTypesAndRefs(t *testing.T) {
	dir := t.TempDir()
	src := `package p

type Kind int64

type Answer struct {
	DryRun       *bool   ` + "`" + `json:"dry_run,omitempty"` + "`" + `
	Blocked, Refused *string ` + "`" + `json:"blocked,omitempty"` + "`" + `
	Hidden       string  ` + "`" + `json:"-"` + "`" + `
	Untagged     string
	rows         []*Row
}

type Row struct{ ID string }
`
	path := filepath.Join(dir, "model.go")
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	types, err := Declared([]string{path})
	if err != nil {
		t.Fatal(err)
	}
	byName := map[string]Type{}
	for _, ty := range types {
		byName[ty.Name] = ty
	}
	if len(types) != 3 {
		t.Fatalf("declared %d types, want 3 (Kind, Answer, Row)", len(types))
	}
	kind := byName["Kind"]
	if kind.Struct {
		t.Error("Kind is an enum, not a struct")
	}
	if len(kind.Refs) != 0 {
		t.Errorf("Kind has no fields but got refs %v", kind.Refs)
	}
	answer := byName["Answer"]
	if !answer.Struct {
		t.Fatal("Answer is a struct")
	}
	goTypes := answer.GoTypes()
	for name, want := range map[string]string{
		"DryRun": "*bool", "Blocked": "*string", "Refused": "*string",
		"Hidden": "string", "Untagged": "string",
	} {
		if got := goTypes[name]; got != want {
			t.Errorf("Go type of %s = %q, want %q", name, got, want)
		}
	}
	jsonTypes := answer.JSONTypes()
	for name, want := range map[string]string{
		"dry_run": "*bool", "blocked": "*string",
	} {
		if got := jsonTypes[name]; got != want {
			t.Errorf("JSON type of %s = %q, want %q", name, got, want)
		}
	}
	if _, ok := jsonTypes["hidden"]; ok {
		t.Error(`json:"-" must not have a contract name`)
	}
	if _, ok := jsonTypes["untagged"]; ok {
		t.Error("an untagged field has no contract name")
	}
	// The dependency edge: what Answer is made of.
	wantRefs := map[string]bool{"bool": true, "string": true, "Row": true}
	for _, r := range answer.Refs {
		delete(wantRefs, r)
	}
	if len(wantRefs) != 0 {
		t.Errorf("Answer refs %v, missing %v", answer.Refs, wantRefs)
	}
}

func TestReferencesCountsMentionsAndSkips(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"tool.go":   "package p\nvar _ = Answer{}\n",
		"other.go":  "package p\n// nothing here\n",
		"gen.go":    "// Code generated by thriftgo. DO NOT EDIT.\npackage p\ntype Answer struct{}\n",
		".git/x.go": "package p\nvar _ = Answer{}\n",
	}
	for name, body := range files {
		full := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	refs, err := References(dir, IsGenerated, []string{"Answer"})
	if err != nil {
		t.Fatal(err)
	}
	got := refs["Answer"]
	if len(got) != 1 || filepath.Base(got[0]) != "tool.go" {
		t.Errorf("Answer referenced in %v, want just tool.go (generated and .git must be skipped)", got)
	}
}

// TestProducedFollowsReferencesTransitively pins the closure the guard
// fires on: a type only reachable THROUGH another produced type is
// produced, and one nobody reaches is not.
func TestProducedFollowsReferencesTransitively(t *testing.T) {
	fields := map[string][]string{
		"Outer":  {"Inner"},
		"Inner":  {"Leaf"},
		"Leaf":   nil,
		"Orphan": {"Inner"},
	}
	got := Produced(fields, []string{"Outer"})
	for _, name := range []string{"Outer", "Inner", "Leaf"} {
		if !got[name] {
			t.Errorf("%s is reachable from a produced type but marked unproduced", name)
		}
	}
	if got["Orphan"] {
		t.Error("Orphan is referenced by nobody and must not be produced")
	}
}
